import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { loadTestRecipes } from './fixtures/test-identities.mjs';
import { buildRecipeSchema, recipeImageUrl } from '../../src/lib/recipe-schema.mjs';
import { exportText } from '../export-text.mjs';
import { checkExports } from '../check-exports.mjs';

const DISHES = 'public/images/dishes';

async function mappedPhotos() {
  const source = await fs.readFile('src/data/dish-visuals.ts', 'utf8');
  return new Map(
    [...source.matchAll(/^ {2}'?([a-z0-9-]+)'?: \{\n {4}file: '([^']+)'/gm)].map((match) => [
      match[1],
      match[2],
    ])
  );
}

test('every recipe with a photo names it by absolute address in JSON-LD', async () => {
  const recipes = await loadTestRecipes();
  const photos = await mappedPhotos();
  const onDisk = new Set(await fs.readdir(DISHES));
  for (const recipe of recipes) {
    if (!photos.has(recipe.slug)) {
      // A new recipe waiting for its photo names none rather than a missing file.
      const { image } = buildRecipeSchema(recipe.data, recipe.body, recipe.url, recipe.parsed, {
        hasPhoto: false,
      });
      assert.equal(image, undefined, recipe.slug);
      assert.ok(!onDisk.has(`${recipe.slug}.webp`), `${recipe.slug}: photo file is not mapped`);
      continue;
    }
    const { image } = buildRecipeSchema(recipe.data, recipe.body, recipe.url, recipe.parsed);
    const file = `${recipe.slug}.webp`;
    assert.deepEqual(image, [`https://jordansilton.com/mise/images/dishes/${file}`], recipe.slug);
    assert.equal(photos.get(recipe.slug), file, `${recipe.slug}: photo map names another file`);
    assert.ok(onDisk.has(file), `${recipe.slug}: photo file is missing`);
  }
});

test('every mapped photo belongs to a live recipe', async () => {
  // A merged or retired recipe must give up its map entry, and its file moves to
  // docs/archive/art/dishes so it no longer ships.
  const live = new Set((await loadTestRecipes()).map((recipe) => recipe.slug));
  const orphans = [...(await mappedPhotos()).keys()].filter((slug) => !live.has(slug));
  assert.deepEqual(orphans, [], 'Mapped photos with no recipe');
});

test('only a recipe page address yields a photo address', () => {
  assert.equal(
    recipeImageUrl('https://example.com/base/recipes/dal-tadka/'),
    'https://example.com/base/images/dishes/dal-tadka.webp'
  );
  for (const url of [undefined, '', '/mise/recipes/dal-tadka/', 'https://example.com/meals/x/'])
    assert.equal(recipeImageUrl(url), null);
  assert.ok(!('image' in buildRecipeSchema({ title: 'T', ingredients: [] }, '', undefined)));
});

test('the image folder holds only mapped recipe photos and one small default share image', async () => {
  const photos = new Set((await mappedPhotos()).values());
  const extra = (await fs.readdir(DISHES)).filter((file) => !photos.has(file));
  assert.deepEqual(extra, [], 'Unmapped files ship with every deploy');
  assert.deepEqual((await fs.readdir('public/images')).sort(), ['dishes', 'share-default.jpg']);
  assert.ok((await fs.stat('public/images/share-default.jpg')).size < 200_000);
  const layout = await fs.readFile('src/layouts/Layout.astro', 'utf8');
  assert.match(layout, /images\/share-default\.jpg/);
  assert.doesNotMatch(layout, /\.png/);
});

test('recipe and meal pages hand their dish photo to the layout', async () => {
  for (const page of ['src/pages/recipes/[slug].astro', 'src/pages/meals/[slug].astro']) {
    const source = await fs.readFile(page, 'utf8');
    assert.match(source, /image=\{socialImage/, page);
    assert.match(source, /RECIPE_IMAGE_SIZE\.width/, page);
  }
});

test('the export check passes fresh files, skips absent ones and fails stale ones', async () => {
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'mise-export-check-'));
  try {
    const text = path.join(dir, 'all-recipes-combined.txt');
    assert.deepEqual((await checkExports(dir, text)).checked, []);
    await exportText(text);
    const result = await checkExports(dir, text);
    assert.deepEqual(result.checked, ['Combined text']);
    assert.deepEqual(result.skipped, ['JSON-LD', 'Paprika']);
    await fs.appendFile(text, 'stale');
    await assert.rejects(checkExports(dir, text), /Combined text is stale/);
  } finally {
    await fs.rm(dir, { recursive: true, force: true });
  }
});

test('the all-recipes text file is generated by the build and not kept in the repository', async () => {
  await assert.rejects(fs.access('public/recipes/all-recipes-combined.txt'));
  assert.match(await fs.readFile('astro.config.mjs', 'utf8'), /astro:build:done/);
});
