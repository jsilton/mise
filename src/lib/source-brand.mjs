const DOMAIN = /\b(?:www\.)?((?:[a-z0-9-]+\.)+(?:com|net|org|co|blog|us|ca|info|io))\b/gi;

export function brandName(domain) {
  const key = domain.toLowerCase().replace(/^www\./, '');
  return BRANDS[key];
}

/** Replaces web addresses in a source line with the publication's name. */
export function brandSource(source = '') {
  return String(source).replace(DOMAIN, (match, domain) => brandName(domain) || match);
}

/**
 * Splits a source into the lead-in ("Adapted from ") and the name that carries the link.
 * Lines that don't start with "Adapted from" link as a whole.
 */
export function sourceParts(source = '') {
  const text = brandSource(source).trim();
  const lead = text.match(/^(Adapted from|From|Inspired by)\s+/i);
  return lead ? { lead: lead[0], name: text.slice(lead[0].length) } : { lead: '', name: text };
}
